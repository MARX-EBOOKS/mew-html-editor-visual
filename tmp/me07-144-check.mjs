import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const window = {};
vm.runInNewContext(await readFile('public/pdfdiff/local-ocr-text-reader.js','utf8') + await readFile('public/pdfdiff/pdf-selection-diff.js','utf8'), {window, URL, location: {href:'http://localhost:17000/'}, fetch});
const api=window.PdfSelectionDiff;
const locator=api.createLocator({}, {document:{createElement:()=>({})},isCurrent:()=>true,waitForIdle:async()=>{}});
const manifestUrl='http://localhost:17000/OCR_DATA/mew_band07.cf7cd20e6c41f466/manifest.json';
const manifest=await (await fetch(manifestUrl)).json();
const pdf={numPages:manifest.page_count,ocrTextUrl:manifestUrl};
const full=await locator.indexDocument(pdf);
const index=locator.sourceIndex(await readFile('../MEW_BRIEF/7/ME07-144.html','utf8'));
const near=full.pages.filter(p=>p.label==='144'|| p.number>=167&&p.number<=169);
console.log('pages',near.map(p=>({number:p.number,label:p.label,start:p.start,end:p.end,text:full.raw.slice(p.start,p.start+65)})));
locator.prepareSource(index,[],pdf);
const connections=index.connections.get(full)||[];
console.log('connections',connections.map(c=>({start:c.start,end:c.end,targetStart:c.targetStart,targetEnd:c.targetEnd,distance:c.distance})));
const items=api.reviewCandidates(index,[full]);
console.log('items',items.map(i=>({start:i.sourceStart,end:i.sourceEnd,comparison:i.comparison})));
console.log('diffs',connections.map(c=>({html:index.raw.slice(c.start,c.end),pdf:full.raw.slice(c.targetStart,c.targetEnd),diff:c.editorDiff})));
const confirmed=connections.flatMap(c=>api.differences(index,full,c).text);
assert.equal(confirmed.length,4);
assert.ok(confirmed.every(span=>span.end-span.start<=1));
assert.ok(items.every(item=>item.sourceEnd-item.sourceStart<=1));
const broad=connections.find(c=>c.editorDiff.distance>128);
assert.ok(broad);
assert.equal(api.connectionDiff(index,full,broad),null);
console.log('PASS: ME07-144 retains four local differences; the unconfirmed whole-page difference is excluded.');
